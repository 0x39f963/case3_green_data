def main() -> int:
    data = json.loads(OVERLAY_PATH.read_text(encoding="utf-8"))
    tables = data.get("tables", {})

    before_table_count = len(tables)
    before_col_count = sum(len(t.get("columns", {})) for t in tables.values())

    applied: list[tuple[str, str]] = []
    missing: list[tuple[str, str]] = []
    skipped_same: list[tuple[str, str]] = []

    for (tname, cname), patch in REWRITES.items():
        t = tables.get(tname)
        if t is None:
            missing.append((tname, cname))
            continue
        col = (t.get("columns") or {}).get(cname)
        if col is None:
            missing.append((tname, cname))
            continue

        new_desc = patch.get("description")
        new_aliases = patch.get("aliases")
        new_nl = patch.get("nl_phrases")

        changed = False
        if new_desc is not None and col.get("description") != new_desc:
            col["description"] = new_desc
            changed = True
        if new_aliases is not None and col.get("aliases") != new_aliases:
            col["aliases"] = list(new_aliases)
            changed = True
        if new_nl is not None and col.get("nl_phrases") != new_nl:
            col["nl_phrases"] = list(new_nl)
            changed = True

        if changed:
            applied.append((tname, cname))
        else:
            skipped_same.append((tname, cname))

    after_table_count = len(tables)
    after_col_count = sum(len(t.get("columns", {})) for t in tables.values())

    if after_table_count != before_table_count:
        print(f"FAIL: table count changed {before_table_count} -> {after_table_count}")
        return 2
    if after_col_count != before_col_count:
        print(f"FAIL: column count changed {before_col_count} -> {after_col_count}")
        return 2
    if missing:
        print("FAIL: некоторые (table, column) пары отсутствуют в overlay:")
        for t, c in missing:
            print(f"  - {t}.{c}")
        return 3

    # backup и запись
    OVERLAY_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    print("=== overlay v2 quality rewrite: PASS ===")
    print(f"tables: {after_table_count}")
    print(f"columns: {after_col_count}")
    print(f"rewrites applied: {len(applied)}")
    print(f"rewrites already in target state: {len(skipped_same)}")
    print(f"missing keys: {len(missing)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
